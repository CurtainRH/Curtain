// Generates contracts/src/lib/PoseidonT3.sol and PoseidonT5.sol: deployers
// for the 2-input and 4-input Poseidon hashers' raw EVM bytecode, produced
// by circomlibjs's own poseidon_gencontract — guaranteeing byte-for-byte
// agreement with circomlib's poseidon.circom (same constants, same package
// family), which is what CurtainPool's on-chain Merkle tree (2-input) and
// note commitments (4-input: tokenId, rawAmount, ownerPkX, blinding) must
// match the ZK circuits on.
const path = require("path");
const fs = require("fs");

const gencontract = require(path.resolve(__dirname, "../node_modules/circomlibjs/src/poseidon_gencontract.js"));

function render(name, nInputs) {
  const bytecodeHex = gencontract.createCode(nInputs).replace(/^0x/, "");
  const inputsType = `uint256[${nInputs}]`;

  return `// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;

/// @notice Deploys the ${nInputs}-input Poseidon hasher as raw EVM bytecode,
/// generated by circomlibjs's poseidon_gencontract (see
/// circuits/scripts/gen-poseidon-solidity.cjs) to guarantee byte-for-byte
/// agreement with circomlib's poseidon.circom constants — the same hasher
/// bytecode pattern used in production by Tornado Cash / Semaphore-style
/// deployments. Kept as a standalone deployer, not a library inlined into
/// callers, so its embedded bytecode doesn't count against any other
/// contract's EIP-170 size limit.
///
/// Regenerate with: node circuits/scripts/gen-poseidon-solidity.cjs
contract ${name}Deployer {
    address public immutable hasher;

    constructor() {
        bytes memory bytecode = _bytecode();
        address addr;
        assembly {
            addr := create(0, add(bytecode, 0x20), mload(bytecode))
        }
        require(addr != address(0), "${name}Deployer: deploy failed");
        hasher = addr;
    }

    function _bytecode() private pure returns (bytes memory) {
        return hex"${bytecodeHex}";
    }
}

/// @notice ABI for the deployed Poseidon(${nInputs}) hasher contract.
interface I${name} {
    function poseidon(${inputsType} calldata inputs) external pure returns (uint256);
}
`;
}

const targets = [
  { name: "PoseidonT3", nInputs: 2 },
  { name: "PoseidonT5", nInputs: 4 },
];

for (const { name, nInputs } of targets) {
  const solidity = render(name, nInputs);
  const outPath = path.resolve(__dirname, `../../contracts/src/lib/${name}.sol`);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, solidity);
  console.log(`Wrote ${outPath}`);
}
